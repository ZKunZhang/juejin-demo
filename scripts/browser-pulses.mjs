import { chromium, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';
import assert from 'node:assert/strict';
import pg from 'pg';

const base=process.env.BROWSER_BASE_URL||'http://127.0.0.1:5173';
const username='pulse_browser_'+randomBytes(6).toString('hex');
const name='沸点浏览器 '+Date.now();
const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||undefined});
try {
  const page=await browser.newPage();
  await page.goto(base+'/register?next=/pulses');
  await page.getByLabel('用户名').fill(username);
  await page.getByLabel('昵称').fill(name);
  await page.getByLabel('密码',{exact:true}).fill(randomBytes(12).toString('hex'));
  await page.getByRole('button',{name:'注册',exact:true}).click();
  await page.waitForURL(base+'/pulses');
  await page.getByLabel('分享动态').fill(name);
  await page.getByLabel('图片地址').fill('https://example.com/image.png');
  await page.getByRole('button',{name:'提交审核',exact:true}).click();
  const item=page.locator('.pulse-card').filter({hasText:name});
  await page.getByText('已提交，等待审核',{exact:true}).waitFor();
  assert.equal(await item.count(),0);
  const admin=await browser.newPage();
  await admin.goto(base+'/admin/login');
  await admin.getByLabel('用户名').fill('admin_demo');
  await admin.getByLabel('密码',{exact:true}).fill(process.env.DEMO_ADMIN_PASSWORD);
  await admin.getByRole('button',{name:'登录',exact:true}).click();
  await admin.getByRole('link',{name:'沸点管理',exact:true}).click();
  const pending=admin.getByRole('table',{name:/^(沸点管理|精选沸点)列表$/}).getByRole('row').filter({
    has: admin.getByRole('cell',{name,exact:true}),
  });
  await pending.getByRole('button',{name:'审核',exact:true}).click();
  const dialog=admin.getByRole('dialog');
  const approving=admin.waitForResponse(res=>res.url().includes('/api/admin/pulses/')&&res.request().method()==='PATCH');
  await dialog.getByRole('button',{name:'审核通过',exact:true}).click();
  const approval=await approving;
  assert.equal(approval.status(),200);
  const {id:pulseId}=await approval.json();
  await pending.getByRole('button',{name:'设为精选',exact:true}).click();
  await dialog.getByRole('button',{name:'设为精选',exact:true}).click();
  await admin.getByText('已设为精选',{exact:true}).waitFor();
  await admin.getByRole('link',{name:'精选沸点',exact:true}).click();
  await pending.getByRole('button',{name:'取消精选',exact:true}).click();
  await dialog.getByRole('button',{name:'取消精选',exact:true}).click();
  await admin.getByText('已取消精选',{exact:true}).waitFor();
  const pulseView=base+'/api/pulses/'+pulseId+'/views';
  const viewing=page.waitForResponse(res=>res.url()===pulseView&&res.request().method()==='POST');
  await page.goto(base+'/pulses?tab=latest');
  await item.getByRole('img').waitFor();
  await item.locator('.article-meta').first().scrollIntoViewIfNeeded();
  const view=await viewing;
  assert.equal(view.status(),200);
  assert.equal((await view.json()).viewCount,1);
  await item.getByRole('button',{name:'点赞 · 0',exact:true}).click();
  await item.getByRole('button',{name:'取消点赞 · 1',exact:true}).waitFor();
  await page.getByRole('button',{name:'今日签到',exact:true}).click();
  await page.getByRole('button',{name:'今日已签到',exact:true}).waitFor();
  await page.reload();
  await item.getByRole('button',{name:'取消点赞 · 1',exact:true}).waitFor();
  await page.getByRole('button',{name:'今日已签到',exact:true}).waitFor();
  await item.getByRole('button',{name:'评论 · 0',exact:true}).click();
  await item.getByLabel('发表评论').fill('沸点评论 '+name);
  await item.getByRole('button',{name:'发表评论',exact:true}).click();
  await item.getByText('沸点评论 '+name,{exact:true}).waitFor();
  await admin.getByRole('link',{name:'评论管理',exact:true}).click();
  await expect(admin.getByRole('link',{name:'文章评论',exact:true})).toHaveAttribute('aria-current','page');
  await admin.getByRole('link',{name:'沸点管理',exact:true}).click();
  await pending.getByRole('link',{name:'评论审核（1）',exact:true}).click();
  await expect(admin).toHaveURL(base+'/admin/comments/pulses?pulseId='+pulseId);
  const comment=admin.locator('.admin-comment').filter({hasText:'沸点评论 '+name});
  await comment.getByLabel('隐藏原因').fill('浏览器验收隐藏');
  await comment.getByRole('button',{name:'隐藏评论'}).click();
  await comment.getByRole('button',{name:'恢复评论'}).waitFor();
  await page.reload();
  await expect(item.getByRole('button',{name:'评论 · 0',exact:true})).toBeVisible();
  await comment.getByRole('button',{name:'恢复评论'}).click();
  await comment.getByRole('button',{name:'隐藏评论'}).waitFor();
  await page.reload();
  await expect(item.getByRole('button',{name:'评论 · 1',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'社区排行榜',exact:true}).click();
  await expect(page.getByRole('heading',{name:'社区排行榜'})).toBeVisible();
  await expect(page.getByRole('table',{name:'沸点人气榜'})).toBeVisible();
  await admin.getByRole('link',{name:'社区排行榜',exact:true}).click();
  await expect(admin.getByRole('heading',{name:'社区排行榜'})).toBeVisible();
  await expect(admin.getByRole('table',{name:'社区排行榜'})).toBeVisible();
  await admin.getByRole('button',{name:'查看详情',exact:true}).first().click();
  await expect(dialog.getByText(/当前排名第 1 名/)).toBeVisible();
  await dialog.getByRole('button',{name:'关闭',exact:true}).click();
  await admin.getByRole('link',{name:'沸点管理',exact:true}).click();
  await expect(pending.getByRole('cell').nth(4)).toHaveText('1');
  await pending.getByRole('button',{name:'下架',exact:true}).click();
  await dialog.getByLabel('下架原因').fill('浏览器验收下架');
  await dialog.getByRole('button',{name:'下架',exact:true}).click();
  await expect(pending.getByText('已下架',{exact:true})).toBeVisible();
  await page.goto(base+'/pulses');
  await page.setViewportSize({width:320,height:720});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  console.log('Chrome 沸点审核、精选、下架、浏览、评论跳转与隐藏恢复、排行榜、点赞和签到通过。');
} finally {
  await browser.close();
  const db=new pg.Client({connectionString:process.env.DATABASE_URL});
  await db.connect();
  try {
    await db.query('DELETE FROM pulses WHERE author_id=(SELECT id FROM users WHERE username=$1)',[username]);
    await db.query('DELETE FROM users WHERE username=$1',[username]);
  }finally{await db.end();}
}
